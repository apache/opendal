/// BlockWrite is used to implement [`oio::Write`] based on block
/// uploads. By implementing BlockWrite, services don't need to
/// care about the details of uploading blocks.
///
/// # Architecture
///
/// The architecture after adopting [`BlockWrite`]:
///
/// - Services impl `BlockWrite`
/// - `BlockWriter` impl `Write`
/// - Expose `BlockWriter` as `Service::Writer`
///
/// # Notes
///
/// `BlockWrite` has an oneshot optimization when `write` has been called only once:
///
/// ```no_build
/// w.write(bs).await?;
/// w.close().await?;
/// ```
///
/// We will use `write_once` instead of starting a new block upload.
///
/// # Requirements
///
/// Services that implement `BlockWrite` must fulfill the following requirements:
///
/// - Must be a http service that could accept `AsyncBody`.
/// - Don't need initialization before writing.
/// - Block ID is generated by caller `BlockWrite` instead of services.
/// - Complete block by an ordered block id list.
pub trait BlockWrite: Send + Sync + Unpin + 'static {
    /// `write_once` writes all data to storage in a single operation.
    ///
    /// BlockWriter will call this API when:
    ///
    /// - The buffer contains all data, so `BlockWriter` can upload it in one
    ///   operation, for example, in a single network request.
    fn write_once(
        &self,
        size: u64,
        body: Buffer,
    ) -> impl Future<Output = Result<Metadata>> + MaybeSend;

    /// write_block will write a block of the data.
    ///
    /// BlockWriter will call this API and stores the result in
    /// order.
    ///
    /// - block_id is the id of the block.
    fn write_block(
        &self,
        block_id: Uuid,
        size: u64,
        body: Buffer,
    ) -> impl Future<Output = Result<()>> + MaybeSend;

    /// complete_block will complete the block upload to build the final
    /// file.
    fn complete_block(
        &self,
        block_ids: Vec<Uuid>,
    ) -> impl Future<Output = Result<Metadata>> + MaybeSend;

    /// abort_block will cancel the block upload and purge all data.
    fn abort_block(&self, block_ids: Vec<Uuid>) -> impl Future<Output = Result<()>> + MaybeSend;
}

struct WriteInput<W: BlockWrite> {
    w: Arc<W>,
    executor: Executor,
    block_id: Uuid,
    bytes: Buffer,
}

enum State {
    /// The writer is active and can accept writes, close, or abort.
    Running,
    /// A close has been initiated and can be retried or aborted.
    Closing,
    /// An abort has been requested and server-side cleanup is pending retry.
    Aborting,
    /// The writer completed and committed the object.
    Completed,
    /// The writer was aborted and any intermediate state was cleaned up.
    Aborted,
}

/// BlockWriter will implement [`oio::Write`] based on block
/// uploads.
pub struct BlockWriter<W: BlockWrite> {
    w: Arc<W>,
    executor: Executor,

    /// Block IDs scheduled for upload, in submission order.
    ///
    /// The IDs remain here until `complete_block` or `abort_block` succeeds, so
    /// a failed close or abort can be retried with the complete list.
    scheduled_block_ids: Vec<Uuid>,
    cache: Option<Buffer>,
    state: State,
    tasks: ConcurrentTasks<WriteInput<W>, Uuid>,
}

impl<W: BlockWrite> BlockWriter<W> {
    /// Create a new BlockWriter.
    pub fn new(executor: impl Into<Executor>, inner: W, concurrent: usize) -> Self {
        let executor = executor.into();

        Self {
            w: Arc::new(inner),
            executor: executor.clone(),
            scheduled_block_ids: Vec::new(),
            cache: None,
            state: State::Running,

            tasks: ConcurrentTasks::new(executor, concurrent, 0, |input| {
                Box::pin(async move {
                    let fut = input
                        .w
                        .write_block(
                            input.block_id,
                            input.bytes.len() as u64,
                            input.bytes.clone(),
                        )
                        .map_ok(|_| input.block_id);
                    match input.executor.timeout() {
                        None => {
                            let result = fut.await;
                            (input, result)
                        }
                        Some(timeout) => {
                            let result = select! {
                                result = fut.fuse() => {
                                    result
                                }
                                _ = timeout.fuse() => {
                                      Err(Error::new(
                                            ErrorKind::Unexpected, "write block timeout")
                                                .with_context("block_id", input.block_id.to_string())
                                                .set_temporary())
                                }
                            };
                            (input, result)
                        }
                    }
                })
            }),
        }
    }

    fn fill_cache(&mut self, bs: Buffer) -> usize {
        let size = bs.len();
        assert!(self.cache.is_none());
        self.cache = Some(bs);
        size
    }
}

impl<W> oio::Write for BlockWriter<W>
where
    W: BlockWrite,
{
    async fn write(&mut self, bs: Buffer) -> Result<()> {
        match self.state {
            State::Running => {}
            State::Closing => {
                return Err(Error::new(
                    ErrorKind::Unexpected,
                    "block writer is closing and can't accept more writes",
                ));
            }
            State::Completed => {
                return Err(Error::new(
                    ErrorKind::Unexpected,
                    "block writer has already been closed",
                ));
            }
            State::Aborting | State::Aborted => {
                return Err(Error::new(
                    ErrorKind::Unexpected,
                    "block writer has already been aborted",
                ));
            }
        }

        if self.scheduled_block_ids.is_empty() && self.cache.is_none() {
            self.fill_cache(bs);
            return Ok(());
        }

        let bytes = self.cache.clone().expect("pending write must exist");
        let block_id = Uuid::new_v4();
        self.tasks
            .execute(WriteInput {
                w: self.w.clone(),
                executor: self.executor.clone(),
                block_id,
                bytes,
            })
            .await?;
        // Record the block only after the task was accepted, so an attempt that
        // never started cannot leak into the ordered completion list.
        self.scheduled_block_ids.push(block_id);
        self.cache = None;
        self.fill_cache(bs);
        Ok(())
    }

    async fn close(&mut self) -> Result<Metadata> {
        match self.state {
            State::Running | State::Closing => {}
            State::Completed => {
                return Err(Error::new(
                    ErrorKind::Unexpected,
                    "block writer has already been closed",
                ));
            }
            State::Aborting | State::Aborted => {
                return Err(Error::new(
                    ErrorKind::Unexpected,
                    "block writer has already been aborted and can't be closed",
                ));
            }
        }

        self.state = State::Closing;

        if self.scheduled_block_ids.is_empty() {
            let (size, body) = match self.cache.clone() {
                Some(cache) => (cache.len(), cache),
                None => (0, Buffer::new()),
            };

            let meta = self.w.write_once(size as u64, body).await?;
            self.cache = None;
            self.state = State::Completed;
            return Ok(meta);
        }

        if let Some(cache) = self.cache.clone() {
            let block_id = Uuid::new_v4();
            self.tasks
                .execute(WriteInput {
                    w: self.w.clone(),
                    executor: self.executor.clone(),
                    block_id,
                    bytes: cache,
                })
                .await?;
            self.scheduled_block_ids.push(block_id);
            self.cache = None;
        }

        while self.tasks.next().await.transpose()?.is_some() {}

        let block_ids = self.scheduled_block_ids.clone();
        let meta = self.w.complete_block(block_ids).await?;
        self.scheduled_block_ids.clear();
        self.state = State::Completed;
        Ok(meta)
    }

    async fn abort(&mut self) -> Result<()> {
        match self.state {
            State::Completed | State::Aborted => return Ok(()),
            State::Running | State::Closing | State::Aborting => {}
        }

        self.state = State::Aborting;
        self.tasks.clear();
        self.cache = None;

        if !self.scheduled_block_ids.is_empty() {
            // Keep the IDs until the abort succeeds so a temporary failure can be retried.
            self.w.abort_block(self.scheduled_block_ids.clone()).await?;
            self.scheduled_block_ids.clear();
        }

        self.state = State::Aborted;
        Ok(())
    }
}

