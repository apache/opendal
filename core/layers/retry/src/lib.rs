/// `RetryLayer` retries temporarily failed operations.
///
/// # Notes
///
/// This layer retries an operation when [`Error::is_temporary`] returns `true`.
/// If the operation still fails, the layer marks the error as `Persistent` to
/// indicate that retries did not resolve it.
/// When a temporary error carries a [retry hint](Error::retry_after), the layer
/// waits at least that long, up to the [maximum delay](Self::with_max_delay).
/// A hint above the maximum ends the operation immediately.
///
/// # Stateful operation bodies
///
/// While retrying stateful operation bodies, please make sure either:
///
/// - All futures generated by the body methods are resolved to `Ready`.
/// - Or, no methods on the same body are called after retry returns a final error.
///
/// Otherwise, `RetryLayer` can lose the inner body state and fail subsequent calls with an
/// `Unexpected` error.
///
/// For example, while composing `RetryLayer` with `TimeoutLayer`. The order of layer is sensitive.
///
/// ```no_run
/// # use std::time::Duration;
/// #
/// # use opendal_core::services;
/// # use opendal_core::Operator;
/// # use opendal_core::Result;
/// # use opendal_layer_retry::RetryLayer;
/// # use opendal_layer_timeout::TimeoutLayer;
/// #
/// # fn main() -> Result<()> {
/// let op = Operator::new(services::Memory::default())?
///     // This is fine, since timeout happens during retry.
///     .layer(TimeoutLayer::default().with_io_timeout(Duration::from_nanos(1)))
///     .layer(RetryLayer::default())
///     // This is wrong. Timeout layer can drop the retry future before it restores body state.
///     .layer(TimeoutLayer::default().with_io_timeout(Duration::from_nanos(1)));
/// # Ok(())
/// # }
/// ```
///
/// # Examples
///
/// ```no_run
/// # use opendal_core::services;
/// # use opendal_core::Operator;
/// # use opendal_core::Result;
/// # use opendal_layer_retry::RetryLayer;
/// #
/// # fn main() -> Result<()> {
/// let _ = Operator::new(services::Memory::default())?
///     .layer(RetryLayer::default());
/// # Ok(())
/// # }
/// ```
///
/// ## Customize retry interceptor
///
/// RetryLayer accepts [`RetryInterceptor`] to allow users to customize
/// their own retry interceptor logic.
///
/// ```no_run
/// # use std::time::Duration;
/// #
/// # use opendal_core::services;
/// # use opendal_core::Error;
/// # use opendal_core::Operator;
/// # use opendal_core::Result;
/// # use opendal_layer_retry::RetryEvent;
/// # use opendal_layer_retry::RetryInterceptor;
/// # use opendal_layer_retry::RetryLayer;
/// #
/// struct MyRetryInterceptor;
///
/// impl RetryInterceptor for MyRetryInterceptor {
///     fn intercept(&self, event: RetryEvent<'_>) {
///         // do something with event.op, event.err, event.retry_after, event.attempt
///     }
/// }
///
/// # fn main() -> Result<()> {
/// let _ = Operator::new(services::Memory::default())?
///     .layer(RetryLayer::default().with_notify(MyRetryInterceptor));
/// # Ok(())
/// # }
/// ```
pub struct RetryLayer<I: RetryInterceptor = DefaultRetryInterceptor> {
    builder: ExponentialBuilder,
    max_delay: Duration,
    notify: Arc<I>,
}

impl<I: RetryInterceptor> Debug for RetryLayer<I> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("RetryLayer")
            .field("builder", &self.builder)
            .finish_non_exhaustive()
    }
}

impl<I: RetryInterceptor> Clone for RetryLayer<I> {
    fn clone(&self) -> Self {
        Self {
            builder: self.builder,
            max_delay: self.max_delay,
            notify: self.notify.clone(),
        }
    }
}

impl Default for RetryLayer {
    fn default() -> Self {
        let max_delay = Duration::from_secs(60);
        Self {
            builder: ExponentialBuilder::default().with_max_delay(max_delay),
            max_delay,
            notify: Arc::new(DefaultRetryInterceptor),
        }
    }
}

impl RetryLayer {
    /// Create a new [`RetryLayer`].
    pub fn new() -> RetryLayer {
        Self::default()
    }
}

impl<I: RetryInterceptor> RetryLayer<I> {
    /// Set the retry interceptor as new notify.
    ///
    /// ```no_run
    /// use opendal_core::services;
    /// use opendal_core::Operator;
    /// use opendal_layer_retry::RetryLayer;
    ///
    /// fn notify(_event: opendal_layer_retry::RetryEvent<'_>) {}
    ///
    /// let _ = Operator::new(services::Memory::default())
    ///     .expect("must init")
    ///     .layer(RetryLayer::default().with_notify(notify));
    /// ```
    pub fn with_notify<NI: RetryInterceptor>(self, notify: NI) -> RetryLayer<NI> {
        RetryLayer {
            builder: self.builder,
            max_delay: self.max_delay,
            notify: Arc::new(notify),
        }
    }

    /// Set jitter of current backoff.
    ///
    /// If jitter is enabled, ExponentialBackoff will add a random jitter in `[0, min_delay)
    /// to current delay.
    pub fn with_jitter(mut self) -> Self {
        self.builder = self.builder.with_jitter();
        self
    }

    /// Set factor of current backoff.
    ///
    /// # Panics
    ///
    /// This function will panic if input factor smaller than `1.0`.
    pub fn with_factor(mut self, factor: f32) -> Self {
        self.builder = self.builder.with_factor(factor);
        self
    }

    /// Set min_delay of current backoff.
    pub fn with_min_delay(mut self, min_delay: Duration) -> Self {
        self.builder = self.builder.with_min_delay(min_delay);
        self
    }

    /// Set the backoff's maximum delay and the largest accepted retry hint.
    ///
    /// When an error carries a retry hint, this limit also caps the final wait
    /// after jitter. The default is 60 seconds.
    pub fn with_max_delay(mut self, max_delay: Duration) -> Self {
        self.max_delay = max_delay;
        self.builder = self.builder.with_max_delay(max_delay);
        self
    }

    /// Set max_times of current backoff.
    ///
    /// Backoff will return `None` if max times is reaching.
    pub fn with_max_times(mut self, max_times: usize) -> Self {
        self.builder = self.builder.with_max_times(max_times);
        self
    }
}

impl<I: RetryInterceptor> Layer for RetryLayer<I> {
    fn apply_service(&self, inner: Servicer) -> Servicer {
        Arc::new(self.layer(inner))
    }
}

impl<I: RetryInterceptor> RetryLayer<I> {
    fn layer(&self, inner: Servicer) -> RetryService<I> {
        RetryService {
            inner,
            retry: self.clone(),
        }
    }

    fn next_delay(
        &self,
        op: Operation,
        backoff: &mut impl Iterator<Item = (u32, Duration)>,
        err: &Error,
    ) -> Option<Duration> {
        if !err.is_temporary() {
            return None;
        }
        let (attempt, delay) = backoff.next()?;
        let retry_after = match err.retry_after() {
            Some(hint) if hint > self.max_delay => return None,
            Some(hint) => delay.max(hint).min(self.max_delay),
            None => delay,
        };
        self.notify.intercept(RetryEvent {
            op,
            err,
            retry_after,
            attempt,
        });
        Some(retry_after)
    }

    async fn retry<T, F: Future<Output = Result<T>>>(
        &self,
        op: Operation,
        mut call: impl FnMut() -> F,
    ) -> Result<T> {
        self.retry_with_context(op, (), |()| {
            let result = call();
            async move { ((), result.await) }
        })
        .await
        .1
    }

    async fn retry_with_context<C, T, F: Future<Output = (C, Result<T>)>>(
        &self,
        op: Operation,
        mut context: C,
        mut call: impl FnMut(C) -> F,
    ) -> (C, Result<T>) {
        let mut backoff = (1..).zip(self.builder.build());
        loop {
            let (next_context, result) = call(context).await;
            context = next_context;
            let delay = match result {
                Ok(value) => return (context, Ok(value)),
                Err(err) => match self.next_delay(op, &mut backoff, &err) {
                    Some(delay) => delay,
                    None => return (context, Err(err.set_persistent())),
                },
            };
            DefaultSleeper::default().sleep(delay).await;
        }
    }

    fn blocking_retry<T>(&self, op: Operation, mut call: impl FnMut() -> Result<T>) -> Result<T> {
        let mut backoff = (1..).zip(self.builder.build());
        loop {
            let delay = match call() {
                Ok(value) => return Ok(value),
                Err(err) => match self.next_delay(op, &mut backoff, &err) {
                    Some(delay) => delay,
                    None => return Err(err.set_persistent()),
                },
            };
            DefaultBlockingSleeper::default().sleep(delay);
        }
    }
}

/// Context passed to [`RetryInterceptor`] before each retry sleep.
#[non_exhaustive]
#[derive(Debug)]
pub struct RetryEvent<'a> {
    /// The operation being retried.
    pub op: Operation,
    /// The error that triggered the retry.
    pub err: &'a Error,
    /// The duration to wait before the next retry attempt.
    pub retry_after: Duration,
    /// 1-based retry attempt number.
    pub attempt: u32,
}

/// RetryInterceptor observes retry attempts before the retry sleep.
pub trait RetryInterceptor: Send + Sync + 'static {
    /// Called before each retry sleep.
    ///
    /// # Notes
    ///
    /// The intercept must be quick and non-blocking. No heavy IO is
    /// allowed. Otherwise, the retry will be blocked.
    fn intercept(&self, event: RetryEvent<'_>);
}

impl<F> RetryInterceptor for F
where
    F: for<'a> Fn(RetryEvent<'a>) + Send + Sync + 'static,
{
    fn intercept(&self, event: RetryEvent<'_>) {
        self(event);
    }
}

/// The DefaultRetryInterceptor logs each retry error at warn level.
pub struct DefaultRetryInterceptor;

impl RetryInterceptor for DefaultRetryInterceptor {
    fn intercept(&self, event: RetryEvent<'_>) {
        log::warn!(
            target: "opendal::layers::retry",
            "will retry {:?} (attempt {}) after {}s because: {:?}",
            event.op, event.attempt, event.retry_after.as_secs_f64(), event.err
        );
    }
}

#[doc(hidden)]
pub struct RetryService<I: RetryInterceptor> {
    inner: Servicer,
    retry: RetryLayer<I>,
}

impl<I: RetryInterceptor> Debug for RetryService<I> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("RetryService")
            .field("inner", &self.inner)
            .finish_non_exhaustive()
    }
}

impl<I: RetryInterceptor> Service for RetryService<I> {
    type Reader = RetryReader<oio::Reader, I>;
    type Writer = RetryWrapper<oio::Writer, I>;
    type Lister = RetryWrapper<oio::Lister, I>;
    type Deleter = RetryWrapper<oio::Deleter, I>;
    type Copier = RetryWrapper<oio::Copier, I>;
    type Composer = oio::Composer;

    fn info(&self) -> ServiceInfo {
        self.inner.info()
    }

    fn capability(&self) -> Capability {
        self.inner.capability()
    }

    fn compose(&self, ctx: &OperationContext, to: &str, args: OpCompose) -> Result<Self::Composer> {
        self.inner.compose(ctx, to, args)
    }

    async fn create_dir(
        &self,
        ctx: &OperationContext,
        path: &str,
        args: OpCreateDir,
    ) -> Result<RpCreateDir> {
        self.retry
            .retry(Operation::CreateDir, || {
                self.inner.create_dir(ctx, path, args.clone())
            })
            .await
    }

    fn read(&self, ctx: &OperationContext, path: &str, args: OpRead) -> Result<Self::Reader> {
        let reader = self
            .retry
            .blocking_retry(Operation::Read, || self.inner.read(ctx, path, args.clone()))?;

        Ok(RetryReader::new(reader, self.retry.clone()))
    }

    fn write(&self, ctx: &OperationContext, path: &str, args: OpWrite) -> Result<Self::Writer> {
        let writer = self.retry.blocking_retry(Operation::Write, || {
            self.inner.write(ctx, path, args.clone())
        })?;

        Ok(RetryWrapper::new(writer, self.retry.clone()))
    }

    async fn stat(&self, ctx: &OperationContext, path: &str, args: OpStat) -> Result<RpStat> {
        self.retry
            .retry(Operation::Stat, || self.inner.stat(ctx, path, args.clone()))
            .await
    }

    fn delete(&self, ctx: &OperationContext) -> Result<Self::Deleter> {
        let deleter = self
            .retry
            .blocking_retry(Operation::Delete, || self.inner.delete(ctx))?;

        Ok(RetryWrapper::new(deleter, self.retry.clone()))
    }

    fn copy(
        &self,
        ctx: &OperationContext,
        from: &str,
        to: &str,
        args: OpCopy,
    ) -> Result<Self::Copier> {
        let copier = self.retry.blocking_retry(Operation::Copy, || {
            self.inner.copy(ctx, from, to, args.clone())
        })?;

        Ok(RetryWrapper::new(copier, self.retry.clone()))
    }

    async fn rename(
        &self,
        ctx: &OperationContext,
        from: &str,
        to: &str,
        args: OpRename,
    ) -> Result<RpRename> {
        self.retry
            .retry(Operation::Rename, || {
                self.inner.rename(ctx, from, to, args.clone())
            })
            .await
    }

    async fn restore(
        &self,
        ctx: &OperationContext,
        path: &str,
        args: OpRestore,
    ) -> Result<RpRestore> {
        self.retry
            .retry(Operation::Restore, || {
                self.inner.restore(ctx, path, args.clone())
            })
            .await
    }

    fn list(&self, ctx: &OperationContext, path: &str, args: OpList) -> Result<Self::Lister> {
        let lister = self
            .retry
            .blocking_retry(Operation::List, || self.inner.list(ctx, path, args.clone()))?;

        Ok(RetryWrapper::new(lister, self.retry.clone()))
    }

    async fn presign(
        &self,
        ctx: &OperationContext,
        path: &str,
        args: OpPresign,
    ) -> Result<RpPresign> {
        self.retry
            .retry(Operation::Presign, || {
                self.inner.presign(ctx, path, args.clone())
            })
            .await
    }
}

#[doc(hidden)]
pub struct RetryReader<R, I: RetryInterceptor> {
    inner: Arc<R>,
    retry: RetryLayer<I>,
}

impl<R, I: RetryInterceptor> RetryReader<R, I> {
    fn new(inner: R, retry: RetryLayer<I>) -> Self {
        Self {
            inner: Arc::new(inner),
            retry,
        }
    }
}

impl<R: oio::Read + 'static, I: RetryInterceptor> oio::Read for RetryReader<R, I> {
    async fn open(&self, range: BytesRange) -> Result<(RpRead, Box<dyn oio::ReadStreamDyn>)> {
        let (rp, stream) = self
            .retry
            .retry(Operation::Read, || self.inner.open(range))
            .await?;
        Ok((
            rp,
            Box::new(RetryReadStream {
                reader: self.inner.clone(),
                stream: Some(stream),
                range,
                read: 0,
                retry: self.retry.clone(),
            }),
        ))
    }

    async fn read(&self, range: BytesRange) -> Result<(RpRead, Buffer)> {
        self.retry
            .retry(Operation::Read, || self.inner.read(range))
            .await
    }
}

#[doc(hidden)]
pub struct RetryReadStream<R, I: RetryInterceptor> {
    reader: Arc<R>,
    stream: Option<Box<dyn oio::ReadStreamDyn>>,
    range: BytesRange,
    read: u64,
    retry: RetryLayer<I>,
}

impl<R: oio::Read, I: RetryInterceptor> oio::ReadStream for RetryReadStream<R, I> {
    async fn read(&mut self) -> Result<Buffer> {
        let reader = &self.reader;
        let context = (self.stream.take(), self.range, self.read);
        let ((stream, range, read), res) = self
            .retry
            .retry_with_context(
                Operation::Read,
                context,
                |(stream, mut range, mut read)| async move {
                    let mut stream = match stream {
                        Some(stream) => stream,
                        None => {
                            range.advance(read);
                            read = 0;

                            // Broke after the last byte: nothing is left to fetch,
                            // and an empty range has no Range header.
                            if range.size() == Some(0) {
                                return ((None, range, read), Ok(Buffer::new()));
                            }
                            match reader.open(range).await {
                                Ok((_, stream)) => stream,
                                Err(err) => return ((None, range, read), Err(err)),
                            }
                        }
                    };
                    match stream.read().await {
                        Ok(buf) => {
                            read += buf.len() as u64;
                            ((Some(stream), range, read), Ok(buf))
                        }
                        Err(err) => ((None, range, read), Err(err)),
                    }
                },
            )
            .await;

        self.stream = stream;
        self.range = range;
        self.read = read;
        res
    }
}

#[doc(hidden)]
pub struct RetryWrapper<R, I: RetryInterceptor> {
    inner: Option<R>,
    retry: RetryLayer<I>,
}

impl<R, I: RetryInterceptor> RetryWrapper<R, I> {
    fn new(inner: R, retry: RetryLayer<I>) -> Self {
        Self {
            inner: Some(inner),
            retry,
        }
    }

    async fn retry<T, F: Future<Output = (R, Result<T>)>>(
        &mut self,
        op: Operation,
        call: impl FnMut(R) -> F,
    ) -> Result<T> {
        let inner = self.inner.take().ok_or_else(|| {
            Error::new(
                ErrorKind::Unexpected,
                "retry layer is in bad state, please make sure future not dropped before ready",
            )
        })?;
        let (inner, result) = self.retry.retry_with_context(op, inner, call).await;
        self.inner = Some(inner);
        result
    }
}

impl<R: oio::ReadStream, I: RetryInterceptor> oio::ReadStream for RetryWrapper<R, I> {
    async fn read(&mut self) -> Result<Buffer> {
        self.retry(Operation::Read, |mut inner| async move {
            let res = inner.read().await;
            (inner, res)
        })
        .await
    }
}

impl<R: oio::Write, I: RetryInterceptor> oio::Write for RetryWrapper<R, I> {
    async fn write(&mut self, bs: Buffer) -> Result<()> {
        self.retry(Operation::Write, |mut inner| {
            let bs = bs.clone();
            async move {
                let res = inner.write(bs).await;
                (inner, res)
            }
        })
        .await
    }

    async fn copy_from(&mut self, path: &str, args: OpRead, range: BytesRange) -> Result<()> {
        self.retry(Operation::Write, |mut inner| {
            let args = args.clone();
            async move {
                let res = inner.copy_from(path, args, range).await;
                (inner, res)
            }
        })
        .await
    }

    async fn abort(&mut self) -> Result<()> {
        self.retry(Operation::Write, |mut inner| async move {
            let res = inner.abort().await;
            (inner, res)
        })
        .await
    }

    async fn close(&mut self) -> Result<Metadata> {
        self.retry(Operation::Write, |mut inner| async move {
            let res = inner.close().await;
            (inner, res)
        })
        .await
    }
}

